import uuid
from datetime import date, datetime
from decimal import Decimal

from sqlalchemy import (
    Boolean,
    CheckConstraint,
    Date,
    DateTime,
    ForeignKey,
    Index,
    Integer,
    Numeric,
    String,
    Text,
    UniqueConstraint,
    func,
)
from sqlalchemy.dialects.postgresql import UUID
from sqlalchemy.orm import Mapped, mapped_column, relationship

from app.core.db import Base


class DistributionLane(Base):
    """Represents a replenishment lane from a parent distribution center to a destination hub."""

    __tablename__ = "distribution_lanes"
    __table_args__ = (
        UniqueConstraint(
            "tenant_id",
            "source_warehouse_id",
            "dest_warehouse_id",
            name="distribution_lanes_pair_uniq",
        ),
        CheckConstraint("source_warehouse_id <> dest_warehouse_id", name="distribution_lanes_distinct_wh"),
        CheckConstraint("transit_days >= 0", name="distribution_lanes_transit_days_ck"),
        Index("distribution_lanes_tenant_idx", "tenant_id", "is_active"),
    )

    id: Mapped[uuid.UUID] = mapped_column(UUID(as_uuid=True), primary_key=True, default=uuid.uuid4)
    tenant_id: Mapped[uuid.UUID] = mapped_column(UUID(as_uuid=True), nullable=False)
    source_warehouse_id: Mapped[uuid.UUID] = mapped_column(
        UUID(as_uuid=True), ForeignKey("warehouses.id", ondelete="CASCADE"), nullable=False
    )
    dest_warehouse_id: Mapped[uuid.UUID] = mapped_column(
        UUID(as_uuid=True), ForeignKey("warehouses.id", ondelete="CASCADE"), nullable=False
    )
    transit_days: Mapped[int] = mapped_column(Integer, nullable=False, default=2)
    shipping_mode: Mapped[str] = mapped_column(String(32), nullable=False, default="Road")
    carrier_name: Mapped[str | None] = mapped_column(String(128), nullable=True)
    cost_per_kg: Mapped[Decimal] = mapped_column(Numeric(10, 2), nullable=False, default=0)
    is_active: Mapped[bool] = mapped_column(Boolean, nullable=False, default=True)

    created_at: Mapped[datetime] = mapped_column(DateTime(timezone=True), server_default=func.now())
    updated_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True), server_default=func.now(), onupdate=func.now()
    )


class DrpReplenishmentPolicy(Base):
    """Replenishment parameters per Destination Warehouse and Product."""

    __tablename__ = "drp_replenishment_policies"
    __table_args__ = (
        UniqueConstraint("tenant_id", "dest_warehouse_id", "product_id", name="drp_policies_wh_prod_uniq"),
        CheckConstraint(
            "policy_type in ('min_max','lot_for_lot','order_up_to','fixed_order_qty')",
            name="drp_policies_type_ck",
        ),
        Index("drp_policies_wh_idx", "tenant_id", "dest_warehouse_id"),
    )

    id: Mapped[uuid.UUID] = mapped_column(UUID(as_uuid=True), primary_key=True, default=uuid.uuid4)
    tenant_id: Mapped[uuid.UUID] = mapped_column(UUID(as_uuid=True), nullable=False)
    dest_warehouse_id: Mapped[uuid.UUID] = mapped_column(
        UUID(as_uuid=True), ForeignKey("warehouses.id", ondelete="CASCADE"), nullable=False
    )
    product_id: Mapped[uuid.UUID] = mapped_column(
        UUID(as_uuid=True), ForeignKey("products.id", ondelete="CASCADE"), nullable=False
    )
    sku: Mapped[str] = mapped_column(String(64), nullable=False)
    policy_type: Mapped[str] = mapped_column(String(32), nullable=False, default="min_max")
    safety_stock_qty: Mapped[Decimal] = mapped_column(Numeric(20, 4), nullable=False, default=0)
    reorder_point_qty: Mapped[Decimal] = mapped_column(Numeric(20, 4), nullable=False, default=0)
    min_order_qty: Mapped[Decimal] = mapped_column(Numeric(20, 4), nullable=False, default=1)
    order_multiple: Mapped[Decimal] = mapped_column(Numeric(20, 4), nullable=False, default=1)
    target_stock_qty: Mapped[Decimal] = mapped_column(Numeric(20, 4), nullable=False, default=0)

    created_at: Mapped[datetime] = mapped_column(DateTime(timezone=True), server_default=func.now())
    updated_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True), server_default=func.now(), onupdate=func.now()
    )


class PlannedTransferOrder(Base):
    """Planned Transfer Order generated by the Multi-Echelon DRP calculation."""

    __tablename__ = "planned_transfer_orders"
    __table_args__ = (
        UniqueConstraint("tenant_id", "pto_no", name="planned_transfers_tenant_no_uniq"),
        CheckConstraint(
            "status in ('suggested','approved','released','cancelled')",
            name="planned_transfers_status_ck",
        ),
        Index("planned_transfers_tenant_status_idx", "tenant_id", "status"),
        Index("planned_transfers_dest_wh_idx", "tenant_id", "dest_warehouse_id"),
        Index("planned_transfers_run_idx", "tenant_id", "run_id"),
    )

    id: Mapped[uuid.UUID] = mapped_column(UUID(as_uuid=True), primary_key=True, default=uuid.uuid4)
    tenant_id: Mapped[uuid.UUID] = mapped_column(UUID(as_uuid=True), nullable=False)
    pto_no: Mapped[str] = mapped_column(String(32), nullable=False)
    run_id: Mapped[str] = mapped_column(String(64), nullable=False)
    source_warehouse_id: Mapped[uuid.UUID] = mapped_column(
        UUID(as_uuid=True), ForeignKey("warehouses.id", ondelete="RESTRICT"), nullable=False
    )
    dest_warehouse_id: Mapped[uuid.UUID] = mapped_column(
        UUID(as_uuid=True), ForeignKey("warehouses.id", ondelete="RESTRICT"), nullable=False
    )
    product_id: Mapped[uuid.UUID] = mapped_column(
        UUID(as_uuid=True), ForeignKey("products.id", ondelete="RESTRICT"), nullable=False
    )
    sku: Mapped[str] = mapped_column(String(64), nullable=False)
    product_name: Mapped[str] = mapped_column(String(255), nullable=False)
    uom: Mapped[str] = mapped_column(String(16), nullable=False, default="unit")

    suggested_qty: Mapped[Decimal] = mapped_column(Numeric(20, 4), nullable=False)
    firm_qty: Mapped[Decimal] = mapped_column(Numeric(20, 4), nullable=False)
    required_delivery_date: Mapped[date] = mapped_column(Date, nullable=False)
    planned_dispatch_date: Mapped[date] = mapped_column(Date, nullable=False)

    status: Mapped[str] = mapped_column(String(32), nullable=False, default="suggested")
    recommendation_reason: Mapped[str | None] = mapped_column(Text, nullable=True)
    released_transfer_id: Mapped[uuid.UUID | None] = mapped_column(
        UUID(as_uuid=True), ForeignKey("transfers.id", ondelete="SET NULL"), nullable=True
    )
    released_transfer_number: Mapped[str | None] = mapped_column(String(64), nullable=True)

    created_at: Mapped[datetime] = mapped_column(DateTime(timezone=True), server_default=func.now())
    updated_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True), server_default=func.now(), onupdate=func.now()
    )
